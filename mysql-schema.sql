  `file_id` VARCHAR(64) DEFAULT NULL COMMENT '文件ID',
  `file_name` VARCHAR(255) DEFAULT NULL COMMENT '存储文件名',
  `original_file_name` VARCHAR(255) DEFAULT NULL COMMENT '原始文件名',
  `file_path` VARCHAR(500) DEFAULT NULL COMMENT '本地存储路径（storage_type=local 时使用）',
  `file_type` VARCHAR(50) DEFAULT NULL COMMENT '文件MIME类型',
  `file_size` BIGINT NOT NULL DEFAULT 0 COMMENT '文件大小（字节）',
  `md5` VARCHAR(32) DEFAULT NULL COMMENT 'MD5校验值',
  `storage_type` VARCHAR(20) DEFAULT 'minio' COMMENT '存储类型：minio/local',
  `bucket_name` VARCHAR(100) DEFAULT NULL COMMENT 'MinIO桶名',
  `object_key` VARCHAR(255) DEFAULT NULL COMMENT 'MinIO对象key',
  `status` VARCHAR(20) DEFAULT NULL COMMENT '状态',
  `create_by` VARCHAR(50) DEFAULT NULL COMMENT '创建人',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  INDEX `idx_file_id` (`file_id`),
  INDEX `idx_bucket_object` (`bucket_name`, `object_key`),
  INDEX `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='文件元数据表';

-- 文档表（对应 com.javaee.documentservice.entity.Document）
CREATE TABLE IF NOT EXISTS `document` (
  `id` VARCHAR(32) NOT NULL COMMENT '主键UUID（ASSIGN_UUID）',
  `title` VARCHAR(255) DEFAULT NULL COMMENT '标题',
  `content` LONGTEXT COMMENT '内容',
  `summary` TEXT COMMENT '摘要',
  `keywords` VARCHAR(500) DEFAULT NULL COMMENT '关键词',
  `file_id` VARCHAR(64) DEFAULT NULL COMMENT '关联文件ID',
  `user_id` BIGINT DEFAULT NULL COMMENT '用户ID',
  `bucket_name` VARCHAR(100) DEFAULT NULL COMMENT 'MinIO桶名',
  `object_name` VARCHAR(255) DEFAULT NULL COMMENT 'MinIO对象名',
  `status` VARCHAR(20) DEFAULT NULL COMMENT '状态',
  `version` INT DEFAULT 1 COMMENT '版本号',
  `category` VARCHAR(50) DEFAULT NULL COMMENT '分类',
  `tags` VARCHAR(500) DEFAULT NULL COMMENT '标签（JSON 数组字符串）',
  `created_by` VARCHAR(50) DEFAULT NULL COMMENT '创建人',
  `create_time` DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  `update_time` DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  PRIMARY KEY (`id`),
  INDEX `idx_user_id` (`user_id`),
  INDEX `idx_file_id` (`file_id`),
  INDEX `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='文档表';
